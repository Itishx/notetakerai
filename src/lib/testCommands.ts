import type { WorldPreset } from "./hilLoopWorld";

/* ============================================================================
   The tuning corpus. Every command on /commands lives here.

   These are not a demo reel. Each group probes ONE behaviour, and the groups
   that matter most are the ones designed to be failed: a referent with nothing
   on screen to resolve it, two jobs pretending to be one, a send button dressed
   up as a favour, a message that begs for therapy voice. A corpus that only
   contains things he handles is a corpus that teaches nothing.

   Human Intelligence groups carry a world preset, because half of what the loop
   has to get right is "is the thing already in front of me". The same sentence
   is a different test with a thread open than with an inbox open.
   ============================================================================ */

